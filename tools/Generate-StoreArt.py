"""Original geometric icon and promotional illustration, never a game screenshot."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'release/artwork'
OUT.mkdir(parents=True, exist_ok=True)
PALETTE = ['#9af5f2', '#3dc5d6', '#178baf', '#d8ffff', '#56dce4', '#11708d']
POINTS = [(280,300),(744,300),(850,435),(512,820),(174,435),(512,435)]
FACES = [[0,1,5],[1,2,5],[2,3,5],[3,4,5],[4,0,5],[0,5,4]]

def icon(size):
    scale = size / 1024
    image = Image.new('RGB', (size,size), '#143e4b')
    draw = ImageDraw.Draw(image)
    def polygon(points, color): draw.polygon([(int(x*scale),int(y*scale)) for x,y in points],fill=color)
    for y in range(size):
        t = y / size
        draw.line((0,y,size,y),fill=(int(20+12*t),int(62-25*t),int(75-33*t)))
    polygon([(0,780),(180,690),(460,860),(740,730),(1024,810),(1024,1024),(0,1024)], '#845136')
    polygon([(0,860),(280,820),(512,930),(820,870),(1024,950),(1024,1024),(0,1024)], '#b87844')
    for face, color in zip(FACES, PALETTE): polygon([POINTS[i] for i in face],color)
    draw.line([(int(x*scale),int(y*scale)) for x,y in [POINTS[4],POINTS[0],POINTS[1],POINTS[2],POINTS[3],POINTS[4]]], fill='#e4ffff', width=max(1,int(7*scale)))
    for x,y,r in [(225,190,40),(800,200,54),(875,640,24)]:
        polygon([(x,y-r),(x+r*.2,y-r*.2),(x+r,y),(x+r*.2,y+r*.2),(x,y+r),(x-r*.2,y+r*.2),(x-r,y),(x-r*.2,y-r*.2)],'#ffdc72')
    return image

large = icon(2048)
large.resize((1024,1024),Image.Resampling.LANCZOS).save(OUT/'icon-1024.png')
app_art = ROOT / 'Assets/_Project/Art'
app_art.mkdir(parents=True, exist_ok=True)
large.resize((1024,1024),Image.Resampling.LANCZOS).save(app_art/'AppIcon.png')
large.resize((512,512),Image.Resampling.LANCZOS).save(OUT/'icon-512.png')
svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><rect width="1024" height="1024" fill="#143e4b"/>'
for face,color in zip(FACES,PALETTE):
    svg += '<polygon points="'+' '.join(f'{POINTS[i][0]},{POINTS[i][1]}' for i in face)+f'" fill="{color}"/>'
svg += '</svg>'
(OUT/'gem-source.svg').write_text(svg)
feature = Image.new('RGB',(2048,1000),'#143e4b')
feature.paste(icon(850),(50,70))
draw = ImageDraw.Draw(feature)
font_path = Path('C:/Windows/Fonts/arialbd.ttf')
def font(size): return ImageFont.truetype(str(font_path),size) if font_path.exists() else ImageFont.load_default(size=size)
draw.text((950,235),'DIAMOND',font=font(128),fill='#d8ffff')
draw.text((950,390),'MINE TYCOON',font=font(106),fill='#ffdc72')
draw.text((955,570),'Dig. Grow. Discover.',font=font(60),fill='#ffffff')
draw.text((955,800),'Promotional illustration',font=font(30),fill='#a3c9cc')
feature.resize((1024,500),Image.Resampling.LANCZOS).save(OUT/'feature-1024x500.png')
(OUT/'README.md').write_text('Original geometric drafts generated by tools/Generate-StoreArt.py. No reference artwork or extracted assets used. These are icons and a labeled promotional illustration, not gameplay screenshots. The system font is rasterized into the feature graphic; no font file is redistributed. Final branding, quality and store suitability require owner review.\n')
print('Wrote 1024/512 icons, vector gem source, and 1024x500 labeled promotional draft.')
